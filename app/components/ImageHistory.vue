<script setup lang="ts">
// One image history for an entity or a document: the team's uploads and Muse Image results together, each labelled with
// where it came from, who added it and when. Editors upload (button or drop, many at once), caption, pick the one in use,
// download and delete; viewers look and download. Editorial only: images are never canon.
const props = defineProps<{ type: ImageTarget, id: string, name: string, noun: string, editable: boolean, generating?: number, fresh?: string[] }>()
const images = defineModel<ImageItem[]>('images', { required: true })
const emit = defineEmits<{ changed: [] }>()

const NOUN = computed(() => props.noun.charAt(0).toUpperCase() + props.noun.slice(1))
const applyLabel = computed(() => (props.noun === 'image' ? 'Use as image' : `Set as ${props.noun}`))
const removeLabel = computed(() => (props.noun === 'image' ? 'Stop using' : `Remove as ${props.noun}`))
const who = (i: ImageItem) => i.created_by_name ?? 'Unknown'
const describe = (i: ImageItem) => (i.source === 'upload' ? `${i.filename ?? 'This image'}, uploaded by ${who(i)} on ${shortDate(i.created_at)}` : `The image generated by ${who(i)} on ${shortDate(i.created_at)}`)

// Uploads: each file gets a row with its own progress and result. Files go in order, IMAGE_BATCH_FILES per request.
interface Item { key: number, name: string, size: number, state: 'queued' | 'uploading' | 'checking' | 'added' | 'refused', progress: number, message?: string }
const items = ref<Item[]>([])
const added = ref<string[]>([])
const busy = computed(() => items.value.some(i => i.state === 'queued' || i.state === 'uploading' || i.state === 'checking'))
let seq = 0
const queue: [number, File][][] = []
let draining = false

function add(files: File[]) {
  if (!files.length || !props.editable) return
  const fresh: Item[] = files.map((f) => {
    const problem = imageUploadProblem(f)
    return { key: ++seq, name: f.name, size: f.size, state: problem ? 'refused' : 'queued', progress: 0, message: problem ?? undefined }
  })
  if (!busy.value) items.value = []
  items.value = [...items.value, ...fresh]
  const ok = fresh.map((it, n) => [it.key, files[n]!] as [number, File]).filter(([key]) => fresh.find(i => i.key === key)!.state === 'queued')
  for (let n = 0; n < ok.length; n += IMAGE_BATCH_FILES) queue.push(ok.slice(n, n + IMAGE_BATCH_FILES))
  if (!draining) drain()
}

async function drain() {
  draining = true
  let any = false
  while (queue.length) {
    const batch = queue.shift()!
    const rows = batch.map(([key]) => items.value.find(i => i.key === key)!)
    rows.forEach((r) => { r.state = 'uploading' })
    try {
      const res = await sendImages(props.type, props.id, batch.map(([, f]) => f), {
        onProgress: (loaded) => {
          let start = 0
          rows.forEach((r) => {
            r.progress = Math.min(1, Math.max(0, (loaded - start) / Math.max(1, r.size)))
            if (r.progress >= 1) r.state = 'checking'
            start += r.size
          })
        },
      })
      res.results.forEach((x, n) => {
        const r = rows[n]!
        if (x.status === 'added') {
          r.state = 'added'
          r.progress = 1
        } else {
          r.state = 'refused'
          r.message = x.message
        }
      })
      const fresh = res.results.flatMap(x => (x.status === 'added' ? [x.image] : []))
      if (fresh.length) {
        any = true
        added.value.push(...fresh.map(i => i.id))
        images.value = [...fresh, ...images.value]
      }
    } catch (e) {
      rows.forEach((r) => { r.state = 'refused'; r.message = errorMessage(e) })
    }
  }
  draining = false
  if (any) emit('changed')
}

const input = ref<HTMLInputElement>()
const pick = () => input.value?.click()
defineExpose({ pick })
function onPick(e: Event) {
  const el = e.target as HTMLInputElement
  add([...el.files ?? []])
  el.value = ''
}
const { over, on: drop } = useFileDrop(add, () => props.editable)

const done = computed(() => items.value.filter(i => i.state === 'added' || i.state === 'refused').length)
const summary = computed(() => {
  const ok = items.value.filter(i => i.state === 'added').length
  const bad = items.value.length - ok
  return [ok && `${counted(ok, 'image')} added`, bad && `${bad} not added`].filter(Boolean).join(' · ')
})
// While a batch runs every file shows; afterwards only the ones that weren't added stay listed.
const rows = computed(() => (busy.value ? items.value : items.value.filter(i => i.state === 'refused')))
const kb = (n: number) => (n >= 1e6 ? `${(n / 1e6).toFixed(1)} MB` : `${Math.max(1, Math.round(n / 1e3))} KB`)

// Picking, removing (with undo: the image stays here), captions and deletes.
const busyId = ref('')
const actionError = ref('')
const undo = ref<{ id: string, message: string } | null>(null)
async function act(i: ImageItem, fn: () => Promise<unknown>) {
  busyId.value = i.id
  actionError.value = ''
  try {
    await fn()
    emit('changed')
    return true
  } catch (e) {
    actionError.value = errorMessage(e)
    return false
  } finally {
    busyId.value = ''
  }
}
const markApplied = (id: string | null) => { images.value = images.value.map(x => ({ ...x, applied: x.id === id })) }
async function apply(i: ImageItem, restore = false) {
  undo.value = null
  if (await act(i, () => $fetch(`/api/images/${i.id}/apply`, { method: 'POST', body: restore ? { undo: true } : undefined }))) markApplied(i.id)
}
async function unapply(i: ImageItem) {
  const ok = await act(i, () => (props.type === 'entity' ? $fetch(`/api/entities/${props.id}/portrait`, { method: 'DELETE' }) : $fetch(`/api/images/${i.id}/apply`, { method: 'DELETE' })))
  if (!ok) return
  markApplied(null)
  undo.value = { id: i.id, message: `${NOUN.value} removed. The image stays here.` }
}
async function undoRemove() {
  const i = images.value.find(x => x.id === undo.value?.id)
  undo.value = null
  if (i) await apply(i, true)
}
async function remove(i: ImageItem) {
  const ok = await askConfirm({
    title: 'Delete this image?',
    body: `${describe(i)}. The file is removed for good; the audit log keeps a record that it existed.`,
    confirm: 'Delete image',
    danger: true,
  })
  if (ok && await act(i, () => $fetch(`/api/images/${i.id}`, { method: 'DELETE' }))) images.value = images.value.filter(x => x.id !== i.id)
}

const editing = ref('')
const caption = ref('')
function editCaption(i: ImageItem) {
  editing.value = i.id
  caption.value = i.caption
  actionError.value = ''
  nextTick(() => document.querySelector<HTMLTextAreaElement>(`#cap-${i.id}`)?.focus())
}
async function saveCaption(i: ImageItem) {
  const text = caption.value.trim()
  if (text === i.caption) {
    editing.value = ''
    return
  }
  if (await act(i, () => $fetch(`/api/images/${i.id}`, { method: 'PATCH', body: { caption: text } }))) {
    images.value = images.value.map(x => (x.id === i.id ? { ...x, caption: text } : x))
    editing.value = ''
  }
}
function captionKey(ev: KeyboardEvent, i: ImageItem) {
  if (ev.key === 'Escape') { ev.preventDefault(); ev.stopPropagation(); editing.value = '' }
  if (ev.key === 'Enter' && !ev.shiftKey) { ev.preventDefault(); saveCaption(i) }
}
const isNew = (i: ImageItem) => added.value.includes(i.id) || !!props.fresh?.includes(i.id)
</script>

<template>
  <div class="history" :class="{ over }" v-on="drop">
    <input v-if="editable" ref="input" type="file" :accept="IMAGE_UPLOAD_TYPES.join(',')" multiple hidden @change="onPick">
    <div v-if="editable" class="up-bar">
      <UiButton icon="upload" size="sm" @click="pick">Upload images</UiButton>
      <span class="small faint">PNG, JPEG, WebP or GIF, up to {{ IMAGE_MAX_BYTES / 1e6 }} MB each. <span class="hide-sm">Or drop files here.</span></span>
    </div>

    <div v-if="items.length" class="uploads" role="region" aria-label="Uploads">
      <div class="up-head small" :class="{ alone: !rows.length }">
        <span role="status">{{ busy ? `Uploading ${Math.min(done + 1, items.length)} of ${items.length}…` : summary }}</span>
        <button v-if="!busy" type="button" class="linkish" @click="items = []">Clear</button>
      </div>
      <ul v-if="rows.length" class="up-list">
        <li v-for="it in rows" :key="it.key" :class="it.state">
          <UiIcon :name="it.state === 'refused' ? 'conflicts' : it.state === 'added' ? 'check' : 'image'" :size="16" class="up-icon" />
          <div class="up-main">
            <div class="up-name"><span>{{ it.name }}</span><span class="faint">{{ kb(it.size) }}</span></div>
            <div v-if="it.state !== 'refused'" class="bar" :class="it.state" role="progressbar" :aria-label="it.name" aria-valuemin="0" aria-valuemax="100" :aria-valuenow="Math.round(it.progress * 100)"><span :style="{ width: `${Math.round(it.progress * 100)}%` }" /></div>
            <p class="up-result">
              <template v-if="it.state === 'queued'">Waiting…</template>
              <template v-else-if="it.state === 'uploading'">Uploading… {{ Math.round(it.progress * 100) }}%</template>
              <template v-else-if="it.state === 'checking'">Checking the file…</template>
              <template v-else-if="it.state === 'added'">Added</template>
              <span v-else class="bad-text">{{ it.message }}</span>
            </p>
          </div>
        </li>
      </ul>
    </div>

    <p v-if="actionError" class="notice bad" role="alert">{{ actionError }}</p>

    <div v-if="generating || images.length" class="grid">
      <template v-if="generating">
        <div v-for="k in generating" :key="`p${k}`" class="shot placeholder" aria-hidden="true"><span class="spinner" /></div>
      </template>
      <figure v-for="i in images" :key="i.id" class="shot" :class="{ current: i.applied }">
        <a :href="i.url" target="_blank" rel="noopener" class="thumb" :title="`Open full size`">
          <img :src="i.url" :alt="i.caption || (i.source === 'upload' ? `Uploaded image of ${name}` : `Generated image of ${name}`)" loading="lazy">
        </a>
        <figcaption>
          <div v-if="i.applied || isNew(i)" class="tags">
            <UiBadge v-if="i.applied" tone="accent">In use as {{ noun }}</UiBadge>
            <UiBadge v-if="isNew(i)" tone="good">New</UiBadge>
          </div>
          <template v-if="i.source === 'upload'">
            <span class="src"><UiIcon name="upload" :size="14" />Uploaded by {{ who(i) }} · {{ shortDate(i.created_at) }}</span>
            <span v-if="i.filename" class="small faint file" :title="i.filename">{{ i.filename }}</span>
          </template>
          <template v-else>
            <span class="src"><UiIcon name="image" :size="14" />Generated by AI</span>
            <span class="small faint">{{ who(i) }} · {{ dateTime(i.created_at) }}</span>
            <details class="small"><summary>Prompt</summary><p class="prompt">{{ i.prompt }}</p></details>
          </template>

          <form v-if="editing === i.id" class="cap-edit" @submit.prevent="saveCaption(i)">
            <textarea :id="`cap-${i.id}`" v-model="caption" rows="2" :maxlength="IMAGE_CAPTION_MAX" placeholder="What is this? e.g. Final costume, act 2" aria-label="Caption" @keydown="captionKey($event, i)" />
            <div class="row">
              <UiButton size="sm" variant="primary" type="submit" :loading="busyId === i.id">Save</UiButton>
              <UiButton size="sm" variant="ghost" @click="editing = ''">Cancel</UiButton>
            </div>
          </form>
          <template v-else>
            <p v-if="i.caption" class="caption">{{ i.caption }}</p>
            <button v-if="editable" type="button" class="linkish small" @click="editCaption(i)">{{ i.caption ? 'Edit caption' : 'Add caption' }}</button>
          </template>

          <div class="acts">
            <template v-if="editable">
              <UiButton v-if="!i.applied" size="sm" variant="primary" :loading="busyId === i.id" :disabled="!!busyId && busyId !== i.id" @click="apply(i)">{{ applyLabel }}</UiButton>
              <UiButton v-else size="sm" :loading="busyId === i.id" :disabled="!!busyId && busyId !== i.id" @click="unapply(i)">{{ removeLabel }}</UiButton>
            </template>
            <a class="btn sm ghost icon-only" :href="`${i.url}?download=1`" :download="imageFileName(i, name)" aria-label="Download original" title="Download original"><UiIcon name="download" :size="16" /></a>
            <UiButton v-if="editable && !i.applied" size="sm" variant="ghost" icon="trash" class="icon-only" :disabled="!!busyId" aria-label="Delete image" title="Delete image" @click="remove(i)" />
          </div>
        </figcaption>
      </figure>
    </div>
    <div v-else-if="!items.length" class="empty-note">
      <UiIcon name="image" :size="22" />
      <p class="small muted">No images yet.<template v-if="editable"> Upload concept art, character sheets or key art, or generate one. You can pick any of them as the {{ noun }} later.</template></p>
    </div>

    <div v-if="over" class="drop" aria-hidden="true"><UiIcon name="upload" :size="24" /><b>Drop to add to {{ name }}’s images</b><span>The current {{ noun }} stays as it is.</span></div>
    <UndoToast v-if="undo" :message="undo.message" @undo="undoRemove" @close="undo = null" />
  </div>
</template>

